class RNNAttentionCTCModule(pl.LightningModule):
    NUM_BANDS: ClassVar[int] = 2
    ELECTRODE_CHANNELS: ClassVar[int] = 16

    def __init__(
        self,
        in_features: int,
        mlp_features: Sequence[int],
        rnn_hidden_size: int,
        rnn_num_layers: int,
        rnn_dropout: float,
        rnn_type: str,
        optimizer: DictConfig,
        lr_scheduler: DictConfig,
        decoder: DictConfig,
    ) -> None:
        super().__init__()
        self.save_hyperparameters()

        # The output size of the rotation-invariant MLP
        cnn_out_features = self.NUM_BANDS * mlp_features[-1]

        # Model Structure
        self.feature_extractor = nn.Sequential(
            SpectrogramNorm(channels=self.NUM_BANDS * self.ELECTRODE_CHANNELS),
            MultiBandRotationInvariantMLP(
                in_features=in_features,
                mlp_features=mlp_features,
                num_bands=self.NUM_BANDS,
            ),
            nn.Flatten(start_dim=2),
        )
        
        self.rnn_encoder = RNNEncoder(
            input_size=cnn_out_features,
            hidden_size=rnn_hidden_size,
            num_layers=rnn_num_layers,
            dropout=rnn_dropout,
            rnn_type=rnn_type,
            bidirectional=True
        )

        attention_dim = self.rnn_encoder.output_size 
        
        self.attention = nn.MultiheadAttention(
            embed_dim=attention_dim, 
            num_heads=4,     # Splits the 512 features into 4 heads of 128
            dropout=0.1      # Helps prevent overfitting on the new attention weights
        )
        
        # LayerNorm stabilizes the learning of the attention layer
        self.layer_norm = nn.LayerNorm(attention_dim)
        
        self.classifier = nn.Sequential(
            nn.Linear(self.rnn_encoder.output_size, charset().num_classes),
            nn.LogSoftmax(dim=-1),
        )

        self.ctc_loss = nn.CTCLoss(blank=charset().null_class)
        self.decoder = instantiate(decoder)

        metrics = MetricCollection([CharacterErrorRates()])
        self.metrics = nn.ModuleDict(
            {
                f"{phase}_metrics": metrics.clone(prefix=f"{phase}/")
                for phase in ["train", "val", "test"]
            }
        )

    def forward(self, inputs: torch.Tensor) -> torch.Tensor:
        # 1. CNN / Feature Extraction
        x = self.feature_extractor(inputs)
        x = x.contiguous()
        
        # 2. RNN Pass
        # x comes out as (Time, Batch, Features)
        x = self.rnn_encoder(x) 
        
        # --- ADD ATTENTION PASS HERE ---
        # Feed 'x' in as Query, Key, and Value. 
        # We use an underscore '_' to ignore the attention weights tensor for now.
        attn_output, _ = self.attention(query=x, key=x, value=x)
        
        # Residual Connection: Add the original RNN output to the Attention output, 
        # then normalize. This is crucial for stable training!
        x = self.layer_norm(x + attn_output)
        # -------------------------------

        # 3. Classifier Pass
        return self.classifier(x)

